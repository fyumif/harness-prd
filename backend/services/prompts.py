OPTIMIZE_DOCUMENT_PROMPT_TEMPLATE = """你是一名资深产品文档编辑。请根据用户的改写指令，对给定文档内容做局部改写。

# 改写指令
{{instruction}}
（常见操作：扩写、缩写、调整语气、补充验收标准、翻译成英文等；以指令实际内容为准）

# 待改写原文
{{content}}

# 输出要求
1. 只输出改写后的正文，不要输出解释、前后缀说明或 Markdown 代码块包裹。
2. 保留原文的标题层级、编号体系（如 FEAT-xxx）与 Markdown 格式；未被指令涉及的内容保持原样。
3. 改写必须与上下文一致，不得引入原文与需求中不存在的功能、数据或规则。
4. 若指令与原文明显矛盾或无法执行，指出问题并给出原文，不要静默篡改。
"""


def render_optimize_prompt(instruction: str, content: str) -> str:
    """渲染局部改写模板。

    模板使用 ``{{instruction}}`` / ``{{content}}`` 占位（双花括号），
    而非 str.format，因为待改写内容可能本身包含花括号（如 OpenAPI 示例）。
    """
    return OPTIMIZE_DOCUMENT_PROMPT_TEMPLATE.replace(
        "{{instruction}}", instruction
    ).replace("{{content}}", content)
